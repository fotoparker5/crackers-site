const escapeHtml = (value = "") =>
  String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");

const compactDate = (value) => {
  const [, month, day] = value.split("-").map(Number);
  return `${month}.${day}`;
};

const isPast = (date, today) => date < today;

