const renderPick = (pick, { archived = false, today }) => {
  const done = isPast(pick.endDate, today);
  const classes = ["pick", done ? "done" : ""].filter(Boolean).join(" ");
  const tag = done ? "마감" : (archived ? "진행 중" : pick.tag);
  const tagClasses = ["tag", done ? "done" : archived ? "live" : ""].filter(Boolean).join(" ");

  return `<a class="${classes}" href="${escapeHtml(pick.url)}" target="_blank" rel="noopener">${pick.image ? `
        <div class="pick-image"><img src="${escapeHtml(pick.image.src)}" alt="${escapeHtml(pick.image.alt)}" loading="lazy" width="900" height="1200"></div>${pick.image.caption ? `\n        <div class="pick-credit">${escapeHtml(pick.image.caption)}</div>` : ""}` : ""}
        <span class="${tagClasses}">${escapeHtml(tag)}</span>
        <div class="venue">${escapeHtml(pick.venue)}</div>
        <h3>${escapeHtml(pick.title)}</h3>
        <p>${escapeHtml(pick.description)}</p>
        <div class="meta">${compactDate(pick.startDate)}–${pick.startDate.slice(0,4) !== pick.endDate.slice(0,4) ? `${pick.endDate.slice(0,4)}.` : ""}${compactDate(pick.endDate)}${pick.hours ? ` · ${escapeHtml(pick.hours)}` : ""} · ${escapeHtml(pick.price)}</div>
      </a>`;
};

